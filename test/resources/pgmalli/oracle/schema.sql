CREATE TYPE mood AS ENUM ('happy', 'sad');
CREATE TABLE groups (id serial PRIMARY KEY, name text NOT NULL, created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE users (id serial PRIMARY KEY, group_id int NOT NULL REFERENCES groups(id), nick text, name text, mood mood, score int NOT NULL);
CREATE TABLE posts (id bigserial PRIMARY KEY, user_id int NOT NULL REFERENCES users(id), title text NOT NULL, body text, created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE tags (id serial PRIMARY KEY, name text NOT NULL UNIQUE);
CREATE TABLE post_tags (post_id bigint NOT NULL REFERENCES posts(id), tag_id int NOT NULL REFERENCES tags(id), PRIMARY KEY (post_id, tag_id));
CREATE TABLE audits (id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, note text NOT NULL DEFAULT 'n', note_upper text GENERATED ALWAYS AS (upper(note)) STORED);
CREATE TABLE notes (id serial PRIMARY KEY, body text NOT NULL, owner text NOT NULL);
CREATE FUNCTION fill_owner() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN NEW.owner := coalesce(NEW.owner, current_user); RETURN NEW; END $$;
CREATE TRIGGER notes_owner BEFORE INSERT ON notes FOR EACH ROW EXECUTE FUNCTION fill_owner();
CREATE TABLE tickets (id serial PRIMARY KEY, state varchar(16) NOT NULL DEFAULT 'open' CHECK (state IN ('open', 'closed')), kind text CHECK (kind IN ('bug', 'task')));
CREATE DOMAIN posint AS integer CHECK (VALUE > 0);
CREATE DOMAIN label AS text;
CREATE DOMAIN mood_d AS mood;
CREATE TABLE profiles (id serial PRIMARY KEY, rank posint, tag label, feel mood_d);
CREATE TABLE hosts (id serial PRIMARY KEY, ip inet, flags bit(4), doc jsonb);
CREATE TABLE nums (id serial PRIMARY KEY, s smallint NOT NULL DEFAULT 1, i int, b bigint, n numeric(6,2), d double precision, r real, vc varchar(8), lvl int NOT NULL DEFAULT 1 CHECK (lvl IN (1, 2)), moods mood[]);
CREATE TABLE codes (id serial PRIMARY KEY, code text NOT NULL, CONSTRAINT codes_code_key UNIQUE (code) DEFERRABLE INITIALLY DEFERRED);
CREATE TABLE events (id serial PRIMARY KEY, title text NOT NULL);
CREATE TABLE special_events (extra text) INHERITS (events);
CREATE TABLE kinds (id serial PRIMARY KEY, flag boolean, uid uuid, day date, at time, att timetz, ts timestamp, raw bytea, span interval, js json, ch char(2), ints int[], texts text[], bigs bigint[]);
CREATE VIEW active_users AS SELECT id, nick, group_id, mood FROM users WHERE score > 0;
